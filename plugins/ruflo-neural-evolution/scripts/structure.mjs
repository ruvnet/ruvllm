import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFile(join(root, path), 'utf8');
const manifest = JSON.parse(await read('.claude-plugin/plugin.json'));
assert.equal(manifest.name, 'ruflo-neural-evolution');
assert.match(manifest.version, /^\d+\.\d+\.\d+$/);
assert(manifest.keywords.length > 0);
for (const key of ['skills', 'commands', 'agents']) assert.equal(Object.hasOwn(manifest, key), false);
const skill = await read('skills/neural-experiment/SKILL.md');
assert.match(skill, /^---\nname: neural-experiment\ndescription: /);
assert.match(skill, /allowed-tools: mcp__plugin_ruflo-neural-evolution_neural__weight_inspect/);
assert.equal(skill.split('\n').find((line) => line.startsWith('allowed-tools:')).includes('*'), false);
assert.match(await read('commands/neural-inspect.md'), /^---\nname: neural-inspect\ndescription: /);
assert.match(await read('agents/neural-reviewer.md'), /^---\nname: neural-reviewer\ndescription: .+\nmodel: sonnet\ntools: mcp__plugin_ruflo-neural-evolution_neural__weight_inspect/);
const readme = await read('README.md');
assert.match(readme, /@claude-flow\/cli` v3\.6/);
assert.match(readme, /## Namespace coordination/);
assert.match(readme, /ruflo-neural-evolution-<intent>/);
assert.match(readme, /## Verification/);
assert.match(readme, /## Architecture Decisions/);
assert.match(await read('docs/adrs/0001-ruflo-neural-evolution-contract.md'), /Status: Proposed/);
const mcp = JSON.parse(await read('.mcp.json'));
assert.equal(mcp.mcpServers.neural.command, 'node');
assert.deepEqual(mcp.mcpServers.neural.args, ['${CLAUDE_PLUGIN_ROOT}/scripts/server.mjs']);
const { TOOLS } = await import('./server.mjs');
assert.equal(TOOLS.length, 6);
assert(TOOLS.every((tool) => tool.inputSchema.additionalProperties === false));
assert(TOOLS.every((tool) => !/activate|authorize|approve/.test(tool.name)));
console.log(JSON.stringify({ structuralChecks: 20, passed: true, tools: TOOLS.map((t) => t.name) }));
